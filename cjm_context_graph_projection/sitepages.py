"""The site's PROJECTED pages: every series page from its Series, every topic page from its Lens
(design e240183f under the redesign build 8079ae0f; 13753cbf (2), 903bc108 (2)).

A projected page's source file is build output, never committed. Its LOCATION is derived from
the node's active `site_path` (`/series/tutorials/x.html` -> `series/tutorials/x.qmd`, the
born-post rule of 98293e72 applied to pages), so no URL moves; its FRONT MATTER comes from the
node's data through one template per node kind:

- a Series lists its members in their AUTHORED order (IN_SERIES + `after`, `series_order`),
  each numbered;
- a Lens lists the notes it selects, sorted by the Lens's own `view.sort` (sitelisting.sort_rows,
  the one sorter); a Lens whose view groups by `series` lists a member THROUGH its Series page,
  one entry per project (the logs index, design 7657c4a5);
- a Lens whose view layout is `coverage-matrix` projects the Tutorials page instead
  (tutorialspage.py, design 7f200ecb): the grid, the learning paths, the tutorials by task;
- a Lens whose view layout is `library` projects the Library index instead, with a work page
  for every work with units (librarypage.py, design 638b7b85);
- a Lens whose view layout is `category-listing` projects the site's CATEGORY LISTING (design
  ce17606b (3)), the page every chip links into: every public post, its chips filtering it in
  place, and the feed; under the public profile a public post it leaves out refuses the page;
- a Lens whose view layout is `category-index` projects the CATEGORY INDEX and every CATEGORY
  PAGE (categorypages.py, design a62f2499): a page per facet entry that earns one, a redirect stub
  for every entry below the threshold. Planned FIRST, since every chip on every other page links
  the category's page where one exists;
- a Lens whose view layout is `home` projects the HOME PAGE (homepage.py, design e55201e2 and
  amendments 5c3c2662 / 8b4f15d0): a map of the index pages and the category listing its
  selection names, planned LAST, since it reads every other planned page. Each index page states
  its HUBS -- the projected pages it links, in the order it shows them -- for the map to read;
  the category listing's entry reads the posts it lists.

A Series page and a work page are ORDERED collections (`sequence` on the planned entry): the
post navigation, JSON-LD isPartOf and llms.txt walk them in order (638b7b85 (5)).

A RETIRED source (publish_state retired, design amendment e916a4b9) is never listed, under
any profile.

Nothing per-page lives in a template: title, description, image, categories (a Series page's are
the ones MORE THAN HALF of its listed members carry, design ce17606b (4)) and dates come from the
graph, and `date-modified` is DERIVED as the newest updated date
(a literal `date-modified`, else `date`) among the members the page lists. The public profile
lists only public members (a publish_state of `published`, or none on a Note of an archive
type, design amendment c64e07e7); staging lists the drafts too, and a member neither rule
decides refuses the page.

Every listing is the PROJECTED LISTING (sitelisting.py, design 0efb5497 + amendment e66296bd):
markup in the page's body, no Quarto listing key. A listed item's chips are the graph's
(categories.py), never its front matter's (design ce17606b (3)). The category listing and every
category page carry a feed, written after the render from the rendered posts (sitefeeds.py).

Every generated page opens its front matter with the GENERATED marker. A projection removes a
marked page it no longer plans (a moved or retired page) and REFUSES to write over an unmarked
file (a hand page still in the tree) — the build says so, it never overwrites source."""

